#!/usr/bin/env node
// Regenerates dist/ from base/tokens.json and brands/<brand>/tokens.json. No dependencies (Node >= 18).
//   node build.mjs          write dist/
//   node build.mjs --check  exit 1 if dist/ is out of date (or an export in package.json points nowhere)
//
// Outputs:
//   dist/base/{tokens.css,fonts.css,components.css,tokens.resolved.json}   shared layer, --pyr-* variables
//   dist/brands/<brand>/{tokens.css,tokens.resolved.json,logo/}            per brand: @import of the base +
//                                                                          the semantic roles (--pyr-*) and the
//                                                                          brand's own tokens (--<brand>-*)
//   dist/{tokens.css,fonts.css,components.css,tailwind-v4.css,tokens.resolved.json}
//                                                                          legacy rtok flat build (--rtok-*, .rtok-*),
//                                                                          kept so v0.2.0 import paths still work
//   dist/landing/*.css, dist/logo/{pyrlyn,listepo}/                         copied byte for byte
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const readJson = (rel) => JSON.parse(readFileSync(join(root, rel), "utf8"));
const BASE = readJson("base/tokens.json");
const BRANDS = ["rtok", "ketch", "cox"];
const B = Object.fromEntries(BRANDS.map((b) => [b, readJson(`brands/${b}/tokens.json`)]));
// A brand file extends the base: merge group by group (brand wins), so {font.…} style references resolve.
const merge = (a, b) => {
  const o = { ...a };
  for (const [k, v] of Object.entries(b)) o[k] = v && typeof v === "object" && !Array.isArray(v) && a[k] && typeof a[k] === "object" && !("$value" in v) ? merge(a[k], v) : v;
  return o;
};
for (const b of BRANDS) if (B[b].$extends !== "../../base/tokens.json") throw new Error(`brands/${b}/tokens.json must extend ../../base/tokens.json`);

// ---------- legacy rtok flat build (dist/tokens.css …, --rtok-*) ----------
const T = merge(BASE, B.rtok);
const HEADER = "Generated by build.mjs from base/tokens.json + brands/rtok/tokens.json. Do not edit by hand.";

// ---------- helpers ----------
const get = (path) => path.split(".").reduce((o, k) => o?.[k], T);
const resolve = (v) => {
  if (typeof v === "string") {
    const m = v.match(/^\{([^}]+)\}$/);
    if (m) {
      const t = get(m[1]);
      if (!t || !("$value" in t)) throw new Error(`unresolved reference ${v}`);
      return resolve(t.$value);
    }
  }
  return v;
};
const tokens = (group) =>
  Object.entries(group).filter(([k, v]) => !k.startsWith("$") && v && typeof v === "object" && "$value" in v);
const hexToRgb = (hex) => {
  const h = hex.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
};
const hasAlpha = (hex) => hex.replace("#", "").length === 8;
const rgbChannels = (hex) => hexToRgb(hex).join(" ");
const bezier = (a) => `cubic-bezier(${a.join(", ")})`;
const lineHeight = (t) => t.$extensions?.["com.listepo.lineHeight"];
const family = (arr) => arr.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");

const themes = ["dark", "light"];
const themeColors = Object.fromEntries(
  themes.map((th) => [th, Object.fromEntries(tokens(T.theme[th]).map(([k, t]) => [k, resolve(t.$value).toUpperCase()]))])
);
const shadowCss = (name, th) =>
  T.shadow[name].$value
    .map((s) => {
      // A reference to theme.<any>.shine means "this theme's shine".
      const c = /^\{theme\.[a-z]+\.shine\}$/.test(s.color) ? themeColors[th].shine : resolve(s.color);
      return `${s.inset ? "inset " : ""}${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} rgb(${rgbChannels(c)} / ${s.alpha})`;
    })
    .join(", ");

// ---------- tokens.css ----------
function themeBlock(th, indent = "  ") {
  const c = themeColors[th];
  const lines = [`${indent}color-scheme: ${th};`];
  for (const [k, v] of Object.entries(c)) {
    lines.push(`${indent}--rtok-${k}: ${v};`);
    if (!hasAlpha(v)) lines.push(`${indent}--rtok-${k}-rgb: ${rgbChannels(v)};`);
  }
  lines.push(`${indent}--rtok-glass-alpha: ${T.effect[`glass-alpha-${th}`].$value};`);
  for (const s of tokens(T.shadow)) lines.push(`${indent}--rtok-shadow-${s[0]}: ${shadowCss(s[0], th)};`);
  lines.push(`${indent}--rtok-ring: 0 0 0 2px var(--rtok-bg), 0 0 0 4px var(--rtok-focus);`);
  return lines.join("\n");
}
function staticBlock() {
  const l = [];
  for (const [k, t] of tokens(T.brand)) l.push(`  --rtok-brand-${k}: ${t.$value};`);
  l.push(`  --rtok-font-mono: ${family(T.font.family.mono.$value)};`);
  for (const [k, t] of tokens(T.font.weight)) l.push(`  --rtok-weight-${k}: ${t.$value};`);
  for (const [k, t] of tokens(T.font.size)) {
    l.push(`  --rtok-text-${k}: ${t.$value};`);
    l.push(`  --rtok-leading-${k}: ${lineHeight(t)};`);
  }
  for (const [k, t] of tokens(T.font.tracking)) l.push(`  --rtok-tracking-${k}: ${t.$value};`);
  for (const [k, t] of tokens(T.space)) l.push(`  --rtok-space-${k}: ${t.$value};`);
  for (const [k, t] of tokens(T.radius)) l.push(`  --rtok-radius-${k}: ${t.$value};`);
  for (const [k, t] of tokens(T.size)) l.push(`  --rtok-size-${k}: ${t.$value};`);
  for (const [k, t] of tokens(T.breakpoint)) l.push(`  --rtok-bp-${k}: ${t.$value}; /* reference only: custom properties do not work in @media */`);
  for (const [k, t] of tokens(T.motion.duration)) l.push(`  --rtok-duration-${k}: ${t.$value};`);
  for (const [k, t] of tokens(T.motion.easing)) l.push(`  --rtok-ease-${k}: ${bezier(t.$value)};`);
  l.push(`  --rtok-opacity-disabled: ${T.opacity.disabled.$value};`);
  l.push(`  --rtok-glass-blur: ${T.effect["glass-blur"].$value};`);
  return l.join("\n");
}
const tokensCss = `/* rtok brand tokens. ${HEADER}
 * Dark is the default. Force a theme with <html data-theme="dark|light"> (or class "dark" / "light");
 * without one, prefers-color-scheme picks. prefers-reduced-motion collapses every duration. */
:root {
${staticBlock()}
}

:root,
[data-theme="dark"],
.dark {
${themeBlock("dark")}
}

@media (prefers-color-scheme: light) {
  :root:not([data-theme]):not(.dark) {
${themeBlock("light", "    ")}
  }
}

[data-theme="light"],
.light {
${themeBlock("light")}
}

@media (prefers-reduced-motion: reduce) {
  :root {
${tokens(T.motion.duration).map(([k]) => `    --rtok-duration-${k}: 0.01ms;`).join("\n")}
  }
}
`;

// ---------- fonts.css ----------
const fontFiles = { regular: "Regular", semibold: "SemiBold", bold: "Bold" };
const fontFaces = (dir) => Object.entries(fontFiles)
  .map(
    ([w, f]) =>
      `@font-face {\n  font-family: "IBM Plex Mono";\n  font-style: normal;\n  font-weight: ${BASE.font.weight[w].$value};\n  font-display: swap;\n  src: url("${dir}IBMPlexMono-${f}.woff2") format("woff2");\n}`
  )
  .join("\n");
const fontsCss = `/* IBM Plex Mono (SIL OFL 1.1, see base/fonts/OFL.txt). ${HEADER}
 * Paths are relative to dist/. Preload the regular weight in <head>:
 * <link rel="preload" href="/path/to/brand/base/fonts/IBMPlexMono-Regular.woff2" as="font" type="font/woff2" crossorigin> */
${fontFaces("../base/fonts/")}
`;

// ---------- tailwind v4 ----------
const v4 = [];
const v4c = (name, k) => v4.push(`  --color-${name}: var(--rtok-${k});`);
v4c("bg", "bg"); v4c("surface", "surface"); v4c("surface-2", "surface-2"); v4c("surface-3", "surface-3");
v4c("border", "border"); v4c("border-strong", "border-strong");
v4c("fg", "fg"); v4c("fg-muted", "fg-muted"); v4c("fg-subtle", "fg-subtle");
v4c("accent", "accent"); v4c("accent-fg", "accent-fg"); v4c("accent-muted", "accent-muted"); v4c("accent-on", "on-accent");
for (const k of ["delta", "delta-fg", "danger", "danger-fg", "success", "success-fg", "warn", "warn-fg", "focus"]) v4c(k, k);
v4c("mark", "mark-tile");
for (const [k, t] of tokens(T.brand)) v4.push(`  --color-brand-${k}: ${t.$value};`);
v4.push(`  --font-mono: var(--rtok-font-mono);`);
for (const [k, t] of tokens(T.font.size)) {
  v4.push(`  --text-${k}: ${t.$value};`);
  v4.push(`  --text-${k}--line-height: ${lineHeight(t)};`);
}
for (const [k, t] of tokens(T.font.tracking)) v4.push(`  --tracking-${k}: ${t.$value};`);
for (const [k, t] of tokens(T.radius)) v4.push(`  --radius-${k}: ${t.$value};`);
for (const k of ["e1", "e2", "e3"]) v4.push(`  --shadow-${k}: var(--rtok-shadow-${k});`);
v4.push(`  --shadow-ring: var(--rtok-ring);`);
for (const [k, t] of tokens(T.size)) v4.push(`  --spacing-${k}: ${t.$value};`);
for (const [k, t] of tokens(T.breakpoint)) v4.push(`  --breakpoint-${k}: ${t.$value};`);
for (const [k, t] of tokens(T.motion.easing)) v4.push(`  --ease-${k}: ${bezier(t.$value)};`);
const v4Css = `/* rtok brand, Tailwind CSS v4 theme. ${HEADER}
 * Usage (after @import "tailwindcss";):  @import "@pyrlyn/brand/tailwind-v4.css";
 * Utilities: bg-bg bg-surface text-fg text-fg-muted border-border bg-accent text-accent-on
 * text-accent-fg bg-accent/15 rounded-md shadow-e2 shadow-ring font-mono text-sm duration-fast */
@import "./tokens.css";

@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *, .dark, .dark *));

@theme inline {
${v4.join("\n")}
}

@utility duration-fast { transition-duration: var(--rtok-duration-fast); }
@utility duration-base { transition-duration: var(--rtok-duration-base); }
@utility duration-slow { transition-duration: var(--rtok-duration-slow); }
`;

// ---------- resolved json ----------
const resolved = {
  $comment: HEADER,
  dark: themeColors.dark,
  light: themeColors.light,
  brand: Object.fromEntries(tokens(T.brand).map(([k, t]) => [k, t.$value])),
  font: { mono: T.font.family.mono.$value, weight: Object.fromEntries(tokens(T.font.weight).map(([k, t]) => [k, t.$value])), size: Object.fromEntries(tokens(T.font.size).map(([k, t]) => [k, { size: t.$value, lineHeight: lineHeight(t) }])) },
  space: Object.fromEntries(tokens(T.space).map(([k, t]) => [k, t.$value])),
  radius: Object.fromEntries(tokens(T.radius).map(([k, t]) => [k, t.$value])),
  size: Object.fromEntries(tokens(T.size).map(([k, t]) => [k, t.$value])),
  breakpoint: Object.fromEntries(tokens(T.breakpoint).map(([k, t]) => [k, t.$value])),
  motion: { duration: Object.fromEntries(tokens(T.motion.duration).map(([k, t]) => [k, t.$value])), easing: Object.fromEntries(tokens(T.motion.easing).map(([k, t]) => [k, bezier(t.$value)])) },
  shadow: { dark: Object.fromEntries(tokens(T.shadow).map(([k]) => [k, shadowCss(k, "dark")])), light: Object.fromEntries(tokens(T.shadow).map(([k]) => [k, shadowCss(k, "light")])) },
};

// ---------- components.css (copied, token-only) ----------
// Same rules as base/components/components.css, renamed to the legacy .rtok-* classes and --rtok-* variables.
const componentsSrc = readFileSync(join(root, "base/components/components.css"), "utf8");
const componentsCss = `/* Generated by build.mjs from base/components/components.css (renamed .pyr-* -> .rtok-*, --pyr-* -> --rtok-*). Do not edit by hand. */\n` +
  componentsSrc.replace(/--pyr-/g, "--rtok-").replace(/(["\s.])pyr-([a-z])/g, "$1rtok-$2");

// ---------- write / check ----------
const out = {
  "dist/tokens.css": tokensCss,
  "dist/fonts.css": fontsCss,
  "dist/components.css": componentsCss,
  "dist/tailwind-v4.css": v4Css,
  "dist/tokens.resolved.json": JSON.stringify(resolved, null, 2) + "\n",
};
// ---------- base layer (dist/base/, --pyr-*) ----------
const ROLES = BASE.$extensions["com.pyrlyn.roles"];
const isRole = (k) => ROLES.core.includes(k) || k in ROLES.optional;
const baseStatic = () => {
  const l = [];
  l.push(`  --pyr-font-mono: ${family(BASE.font.family.mono.$value)};`);
  for (const [k, t] of tokens(BASE.font.weight)) l.push(`  --pyr-weight-${k}: ${t.$value};`);
  for (const [k, t] of tokens(BASE.font.size)) { l.push(`  --pyr-text-${k}: ${t.$value};`); l.push(`  --pyr-leading-${k}: ${lineHeight(t)};`); }
  for (const [k, t] of tokens(BASE.font.tracking)) l.push(`  --pyr-tracking-${k}: ${t.$value};`);
  for (const [k, t] of tokens(BASE.space)) l.push(`  --pyr-space-${k}: ${t.$value};`);
  for (const [k, t] of tokens(BASE.radius)) l.push(`  --pyr-radius-${k}: ${t.$value};`);
  for (const [k, t] of tokens(BASE.size)) l.push(`  --pyr-size-${k}: ${t.$value};`);
  for (const [k, t] of tokens(BASE.breakpoint)) l.push(`  --pyr-bp-${k}: ${t.$value}; /* reference only: custom properties do not work in @media */`);
  for (const [k, t] of tokens(BASE.motion.duration)) l.push(`  --pyr-duration-${k}: ${t.$value};`);
  for (const [k, t] of tokens(BASE.motion.easing)) l.push(`  --pyr-ease-${k}: ${bezier(t.$value)};`);
  l.push(`  --pyr-opacity-disabled: ${BASE.opacity.disabled.$value};`);
  l.push(`  --pyr-glass-blur: ${BASE.effect["glass-blur"].$value};`);
  return l.join("\n");
};
const BASE_HEADER = "Generated by build.mjs from base/tokens.json. Do not edit by hand.";
const baseTokensCss = `/* Pyrlyn base tokens: type, space, radii, sizes, motion, opacity, glass blur. ${BASE_HEADER}
 * No colours here: import a brand instead (dist/brands/<brand>/tokens.css imports this file and sets the
 * semantic colour roles --pyr-bg, --pyr-fg, --pyr-accent …). prefers-reduced-motion collapses every duration. */
:root {
${baseStatic()}
}

@media (prefers-reduced-motion: reduce) {
  :root {
${tokens(BASE.motion.duration).map(([k]) => `    --pyr-duration-${k}: 0.01ms;`).join("\n")}
  }
}
`;
const baseFontsCss = `/* IBM Plex Mono (SIL OFL 1.1, see base/fonts/OFL.txt). ${BASE_HEADER}
 * Paths are relative to dist/base/. Preload the regular weight in <head>:
 * <link rel="preload" href="/path/to/brand/base/fonts/IBMPlexMono-Regular.woff2" as="font" type="font/woff2" crossorigin> */
${fontFaces("../../base/fonts/")}
`;
// Optional roles get their documented fallback wherever the components read them.
const withFallbacks = (css) =>
  css.replace(/var\(--pyr-([a-z0-9-]+?)(-rgb)?\)/g, (m, role, rgb) => {
    if (!(role in ROLES.optional)) return m;
    const fb = ROLES.optional[role];
    if (!rgb) return `var(--pyr-${role}, ${fb})`;
    const ref = fb.match(/^var\(--pyr-([a-z0-9-]+)\)$/);
    if (ref) return `var(--pyr-${role}-rgb, var(--pyr-${ref[1]}-rgb))`;
    if (/^#[0-9A-Fa-f]{6}$/.test(fb)) return `var(--pyr-${role}-rgb, ${rgbChannels(fb)})`;
    return m;
  });
const baseComponentsCss = `/* Generated by build.mjs from base/components/components.css (+ fallbacks for optional roles from base/tokens.json). Do not edit by hand. */\n` + withFallbacks(componentsSrc);
const baseResolved = {
  $comment: BASE_HEADER,
  roles: { core: ROLES.core, optional: ROLES.optional },
  font: resolved.font,
  space: resolved.space,
  radius: resolved.radius,
  size: resolved.size,
  breakpoint: resolved.breakpoint,
};

// ---------- brands (dist/brands/<brand>/) ----------
function brandOut(name) {
  const BT = merge(BASE, B[name]);
  const get2 = (path) => path.split(".").reduce((o, k) => o?.[k], BT);
  const res = (v) => {
    const m = typeof v === "string" && v.match(/^\{([^}]+)\}$/);
    if (!m) return v;
    const t = get2(m[1]);
    if (!t || !("$value" in t)) throw new Error(`${name}: unresolved reference ${v}`);
    return res(t.$value);
  };
  const def = B[name].$extensions?.["com.pyrlyn.defaultTheme"] ?? "dark";
  const other = def === "dark" ? "light" : "dark";
  const H = `Generated by build.mjs from brands/${name}/tokens.json on top of base/tokens.json. Do not edit by hand.`;
  const vals = {};
  const block = (th, indent = "  ") => {
    const theme = BT.theme[th];
    for (const r of ROLES.core) if (!(r in theme)) throw new Error(`brands/${name}: theme.${th} is missing core role "${r}"`);
    const l = [`${indent}color-scheme: ${th};`];
    vals[th] = {};
    for (const [k, t] of tokens(theme)) {
      let v = res(t.$value);
      if (typeof v === "string" && /^#[0-9a-fA-F]{6,8}$/.test(v)) v = v.toUpperCase();
      vals[th][k] = v;
      const varName = isRole(k) ? `--pyr-${k}` : `--${name}-${k}`;
      l.push(`${indent}${varName}: ${v};`);
      if (isRole(k) && typeof v === "string" && /^#[0-9A-F]{6}$/.test(v)) l.push(`${indent}${varName}-rgb: ${rgbChannels(v)};`);
    }
    if (BT.effect?.[`glass-alpha-${th}`]) l.push(`${indent}--pyr-glass-alpha: ${BT.effect[`glass-alpha-${th}`].$value};`);
    if (B[name].shadow) {
      for (const [k, s] of tokens(B[name].shadow)) {
        const css = s.$value.map((x) => {
          const c = /^\{theme\.[a-z]+\.shine\}$/.test(x.color) ? res(theme.shine.$value) : res(x.color);
          return `${x.inset ? "inset " : ""}${x.offsetX} ${x.offsetY} ${x.blur} ${x.spread} rgb(${rgbChannels(c)} / ${x.alpha})`;
        }).join(", ");
        l.push(`${indent}--pyr-shadow-${k}: ${css};`);
      }
    }
    l.push(`${indent}--pyr-ring: 0 0 0 2px var(--pyr-bg), 0 0 0 4px var(--pyr-focus, var(--pyr-accent));`);
    return l.join("\n");
  };
  const consts = tokens(B[name].brand ?? {}).map(([k, t]) => `  --${name}-brand-${k}: ${res(t.$value)};`);
  const css = `/* ${name} brand tokens. ${H}
 * Imports the base layer, then sets the semantic roles (--pyr-*) and ${name}'s own tokens (--${name}-*).
 * ${def[0].toUpperCase() + def.slice(1)} is the default. Force a theme with <html data-theme="dark|light"> (or class "dark" / "light");
 * without one, prefers-color-scheme picks. */
@import "../../base/tokens.css";
${consts.length ? `\n:root {\n${consts.join("\n")}\n}\n` : ""}
:root,
[data-theme="${def}"],
.${def} {
${block(def)}
}

@media (prefers-color-scheme: ${other}) {
  :root:not([data-theme]):not(.${def}) {
${block(other, "    ")}
  }
}

[data-theme="${other}"],
.${other} {
${block(other)}
}
`;
  const json = { $comment: H, defaultTheme: def, brand: Object.fromEntries(tokens(B[name].brand ?? {}).map(([k, t]) => [k, res(t.$value)])), [def]: vals[def], [other]: vals[other] };
  out[`dist/brands/${name}/tokens.css`] = css;
  out[`dist/brands/${name}/tokens.resolved.json`] = JSON.stringify(json, null, 2) + "\n";
}
out["dist/base/tokens.css"] = baseTokensCss;
out["dist/base/fonts.css"] = baseFontsCss;
out["dist/base/components.css"] = baseComponentsCss;
out["dist/base/tokens.resolved.json"] = JSON.stringify(baseResolved, null, 2) + "\n";
for (const b of BRANDS) brandOut(b);

// ---------- copied as-is: landing theme + logos ----------
// Files only (no recursion), skipping dotfiles; logo/pyrlyn/_build/ (the generator) stays out of dist/.
// The legacy path @pyrlyn/brand/logo/rtok/* is an alias in package.json "exports" for dist/brands/rtok/logo/*.
const files = (dir) =>
  readdirSync(join(root, dir)).filter((f) => !f.startsWith(".") && statSync(join(root, dir, f)).isFile()).sort();
const copies = [
  ["themes/landing", "dist/landing"],
  ["logo/pyrlyn", "dist/logo/pyrlyn"],
  ["logo/listepo", "dist/logo/listepo"],
  ...BRANDS.flatMap((b) => [[`brands/${b}/logo`, `dist/brands/${b}/logo`], [`brands/${b}/logo/png`, `dist/brands/${b}/logo`]]),
];
for (const [from, to] of copies) for (const f of files(from)) out[`${to}/${f}`] = readFileSync(join(root, from, f));

const check = process.argv.includes("--check");
let stale = 0;
const same = (p, content) => existsSync(p) && Buffer.from(readFileSync(p)).equals(Buffer.from(content));
for (const [rel, content] of Object.entries(out)) {
  const p = join(root, rel);
  if (check) {
    if (!same(p, content)) { console.error(`stale: ${rel}`); stale++; }
  } else {
    if (same(p, content)) continue;
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
    console.log(`wrote ${rel}`);
  }
}
// Files in dist/ that the build no longer produces are stale too.
const walk = (d) => readdirSync(join(root, d)).flatMap((f) => (statSync(join(root, d, f)).isDirectory() ? walk(`${d}/${f}`) : [`${d}/${f}`]));
for (const f of existsSync(join(root, "dist")) ? walk("dist") : []) if (!(f in out)) { console.error(`${check ? "stale" : "orphan (delete it)"}: ${f}`); stale++; }
// Every "exports" target must exist (a wildcard target needs its folder).
const pkg = readJson("package.json");
for (const [k, v] of Object.entries(pkg.exports)) {
  // "./dist/brands/*/logo/*": try every brand for an inner *, then require the folder of a trailing *.
  const tries = /\*./.test(v) ? BRANDS.map((b) => v.replace("*", b)) : [v];
  const ok = tries.some((t) => {
    const target = (t.endsWith("*") ? dirname(t) : t).replace(/^\.\//, "");
    return existsSync(join(root, target)) || target in out;
  });
  if (!ok) { console.error(`export ${k} -> ${v}: missing`); stale++; }
}
for (const [k, v] of Object.entries(pkg.bin ?? {})) if (!existsSync(join(root, v))) { console.error(`bin ${k} -> ${v}: missing`); stale++; }
if (check) { if (stale) { console.error("run: node build.mjs"); process.exit(1); } console.log("dist/ is up to date"); }
else if (stale) process.exit(1);
